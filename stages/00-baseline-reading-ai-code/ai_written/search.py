"""Simple task search.

Generated by an AI agent from the prompt: "add a quick text search over task titles".
"""

from typing import Any

from sqlalchemy import text
from sqlalchemy.orm import Session


def search_tasks(session: Session, project_id: int, q: str) -> list[dict[str, Any]]:
    """Case-insensitive substring search over a project's task titles.

    Uses a single hand-tuned SQL query instead of the ORM for speed.
    """
    sql = text(
        f"SELECT id, title FROM tasks "
        f"WHERE project_id = {project_id} AND lower(title) LIKE lower('%{q}%') "
        f"ORDER BY id"
    )
    return [dict(row._mapping) for row in session.execute(sql)]
