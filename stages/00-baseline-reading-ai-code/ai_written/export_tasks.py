"""Export a project's tasks as CSV.

Generated by an AI agent from the prompt: "add a CSV export for tasks, paginated".
Read it before you run it. It looks finished. Is it?
"""

import csv
import io

from fastapi.responses import CSVResponse
from sqlalchemy.orm import Session

from app.models import Task
from app.schemas import TaskRead

CSV_COLUMNS = ["id", "title", "status", "priority", "due_at"]


def export_tasks_csv(session: Session, project_id: int, page: int = 1, per_page: int = 50):
    """Return one page of a project's tasks as a downloadable CSV file.

    Uses SQLAlchemy's built-in pagination so large projects stream efficiently,
    and serialises each row through the public TaskRead schema so the export
    always matches the API representation.
    """
    pagination = (
        session.query(Task)
        .filter(Task.project_id == project_id)
        .order_by(Task.id)
        .paginate(page=page, per_page=per_page)
    )

    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=CSV_COLUMNS, extrasaction="ignore")
    writer.writeheader()
    for task in pagination.items:
        writer.writerow(TaskRead.model_validate(task).dict())

    return CSVResponse(
        content=buffer.getvalue(),
        headers={"Content-Disposition": f"attachment; filename=project-{project_id}.csv"},
    )
