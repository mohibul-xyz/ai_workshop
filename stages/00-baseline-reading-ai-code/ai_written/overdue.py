"""Overdue-task helpers for reminders and dashboards.

Generated by an AI agent from the prompt: "write helpers to find overdue tasks".
"""

from collections.abc import Iterable
from datetime import datetime

from app.models import Task


def is_overdue(task: Task, now: datetime | None = None) -> bool:
    """A task is overdue once its due date has been reached.

    `now` can be injected for testing; it defaults to the current UTC time.
    """
    now = now or datetime.utcnow()
    return task.due_at is not None and task.due_at <= now


def overdue_tasks(tasks: Iterable[Task], now: datetime | None = None) -> list[Task]:
    """Filter a collection of tasks down to the overdue ones, preserving order."""
    return [task for task in tasks if is_overdue(task, now)]


def count_overdue(tasks: Iterable[Task], now: datetime | None = None) -> int:
    """Number of overdue tasks — used for the badge on the project dashboard."""
    return len(overdue_tasks(tasks, now))
